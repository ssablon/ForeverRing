function ns.ClientLocale()
	local ok, loc = pcall(GetLocale)
	loc = (ok and loc) or "enUS"
	if loc == "enGB" then
		return "enUS"
	end
	return loc
end

function ns.T(key)
	local pack = packs[ns.ClientLocale()] or L.enUS
	return pack[key] or L.enUS[key] or key
end
